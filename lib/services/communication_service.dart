import 'package:share_plus/share_plus.dart';
import 'package:url_launcher/url_launcher.dart';
import '../models/customer.dart';
import '../models/sale.dart';

/// Service for sending receipts, warranty notifications, and payment reminders.
/// Uses share intents and external app links for WhatsApp, email, and SMS.
class CommunicationService {
  static const _thankYouMessage = 'Thank you for shopping with Mobile Shop POS.';

  String generateInvoiceMessage(Customer customer, Sale sale) {
    final buffer = StringBuffer();
    buffer.writeln(_thankYouMessage);
    buffer.writeln();
    buffer.writeln('Customer: ${customer.name}');
    buffer.writeln('Phone: ${customer.phone}');
    if (customer.email != null) {
      buffer.writeln('Email: ${customer.email}');
    }
    buffer.writeln('Product: ${sale.productName}');
    buffer.writeln('Quantity: ${sale.quantity}');
    buffer.writeln('Total: Rs ${sale.totalPrice.toStringAsFixed(2)}');
    buffer.writeln('Payment method: ${sale.payment.methodName}');
    if (sale.creditAmount > 0) {
      buffer.writeln('Credit due: Rs ${sale.creditAmount.toStringAsFixed(2)}');
    }
    buffer.writeln('Date: ${sale.date.toIso8601String()}');
    buffer.writeln();
    buffer.writeln('Invoice generated by Mobile Shop POS.');
    return buffer.toString();
  }

  String generateWarrantyMessage({
    required Customer customer,
    required String productName,
    required DateTime purchaseDate,
    required int warrantyMonths,
  }) {
    final expiry = DateTime(purchaseDate.year, purchaseDate.month + warrantyMonths, purchaseDate.day);
    return '''$_thankYouMessage

Warranty activated for $productName.
Customer: ${customer.name}
Phone: ${customer.phone}
Warranty period: $warrantyMonths months
Warranty expiry: ${expiry.toLocal().toIso8601String()}

Keep this message for your records.''';
  }

  String generatePaymentReminder(Customer customer, double dueAmount) {
    return '''$_thankYouMessage

Dear ${customer.name},
Your outstanding balance is Rs ${dueAmount.toStringAsFixed(2)}.
Please complete payment at your earliest convenience.

Mobile Shop POS''';
  }

  Future<void> shareText(String text, {String? subject}) async {
    await Share.share(text, subject: subject);
  }

  String _sanitizePhoneNumber(String phone) {
    return phone.replaceAll(RegExp(r'[^0-9+]'), '').replaceFirst(RegExp(r'^\+'), '');
  }

  Future<bool> sendViaWhatsApp(String message, {String? phone}) async {
    final encoded = Uri.encodeComponent(message);
    if (phone != null && phone.isNotEmpty) {
      final sanitizedPhone = _sanitizePhoneNumber(phone);
      final whatsappUri = Uri.parse('whatsapp://send?phone=$sanitizedPhone&text=$encoded');
      if (await canLaunchUrl(whatsappUri)) {
        return launchUrl(whatsappUri);
      }

      final webUri = Uri.parse('https://wa.me/$sanitizedPhone?text=$encoded');
      if (await canLaunchUrl(webUri)) {
        return launchUrl(webUri);
      }
    }

    final genericUri = Uri.parse('whatsapp://send?text=$encoded');
    if (!await canLaunchUrl(genericUri)) {
      return false;
    }
    return launchUrl(genericUri);
  }

  Future<bool> sendEmail(String email, String subject, String body) async {
    final uri = Uri(scheme: 'mailto', path: email, queryParameters: {
      'subject': subject,
      'body': body,
    });
    if (!await canLaunchUrl(uri)) {
      return false;
    }
    return launchUrl(uri);
  }

  Future<bool> sendSms(String phone, String message) async {
    final sanitizedPhone = _sanitizePhoneNumber(phone);
    final uri = Uri(scheme: 'sms', path: sanitizedPhone, queryParameters: {
      'body': message,
    });
    if (!await canLaunchUrl(uri)) {
      return false;
    }
    return launchUrl(uri);
  }

  Future<void> dispatchInvoice(Customer customer, Sale sale) async {
    final message = generateInvoiceMessage(customer, sale);
    if (customer.phone.isNotEmpty) {
      if (await sendViaWhatsApp(message, phone: customer.phone)) return;
      await sendSms(customer.phone, message);
      return;
    }
    if (customer.email != null && customer.email!.isNotEmpty) {
      await sendEmail(customer.email!, 'Your Mobile Shop POS Invoice', message);
      return;
    }
    await shareText(message, subject: 'Mobile Shop POS Invoice');
  }

  Future<void> dispatchWarrantyNotification({
    required Customer customer,
    required String productName,
    required DateTime purchaseDate,
    required int warrantyMonths,
  }) async {
    final message = generateWarrantyMessage(
      customer: customer,
      productName: productName,
      purchaseDate: purchaseDate,
      warrantyMonths: warrantyMonths,
    );
    if (customer.phone.isNotEmpty) {
      if (await sendViaWhatsApp(message, phone: customer.phone)) return;
      await sendSms(customer.phone, message);
      return;
    }
    if (customer.email != null && customer.email!.isNotEmpty) {
      await sendEmail(customer.email!, 'Your Warranty Details', message);
      return;
    }
    await shareText(message, subject: 'Warranty Details');
  }

  Future<void> dispatchPaymentReminder(Customer customer, double dueAmount) async {
    final message = generatePaymentReminder(customer, dueAmount);
    if (customer.phone.isNotEmpty) {
      if (await sendViaWhatsApp(message, phone: customer.phone)) return;
      await sendSms(customer.phone, message);
      return;
    }
    if (customer.email != null && customer.email!.isNotEmpty) {
      await sendEmail(customer.email!, 'Payment Reminder from Mobile Shop POS', message);
      return;
    }
    await shareText(message, subject: 'Payment Reminder');
  }
}
